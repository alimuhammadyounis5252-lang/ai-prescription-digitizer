def normalize_key(name):
    clean = re.sub(r"^[^\w]+", "", (name or "").strip())
    clean = re.sub(r"^(tab|cap|gp|cp|syp|inj|syr|drops?|cream|oint|t|c)\b[.\s\-_:]*", "", clean, flags=re.I)
    return re.sub(r"[^a-z0-9]", "", clean.lower())


def main():
    root = Path(__file__).resolve().parent.parent
    csv_path = root / "data" / "formulary.csv"

    current = {}
    if csv_path.exists():
        with open(csv_path, encoding="utf-8-sig", newline="") as f:
            lines = [l for l in f if l.strip() and not l.startswith("#")]
        reader = csv.DictReader(lines)
        for r in reader:
            current[normalize_key(r["brand"])] = r

    initial_count = len(current)
    print(f"Loaded existing unique brands: {initial_count}")

    # Add items from DRAP_CATALOG
    added_brands = 0
    for brand, generic, strengths, form in DRAP_CATALOG:
        k = normalize_key(brand)
        if k not in current:
            current[k] = {
                "brand": brand,
                "generic": generic,
                "strengths": strengths,
                "form": form,
                "source": "DRAP",
                "verified": "yes",
            }
            added_brands += 1
        else:
            # Enrich existing item if missing details
            if not current[k].get("generic") and generic:
                current[k]["generic"] = generic
            if not current[k].get("strengths") and strengths:
                current[k]["strengths"] = strengths

    # Also automatically register pure generic formulas as searchable entries
    added_generics = 0
    for brand, generic, strengths, form in DRAP_CATALOG:
        # Split compound generic formulas like 'Amoxicillin + Clavulanate'
        parts = [p.strip() for p in re.split(r"[/+()]", generic) if len(p.strip()) > 3]
        for part in parts:
            gk = normalize_key(part)
            if gk and gk not in current and len(gk) >= 3:
                current[gk] = {
                    "brand": part.title(),
                    "generic": generic,
                    "strengths": strengths,
                    "form": form,
                    "source": "DRAP-Generic",
                    "verified": "yes",
                }
                added_generics += 1

    total = len(current)
    print(f"Added {added_brands} new pharmaceutical brands.")
    print(f"Added {added_generics} standard generic drug keys.")
    print(f"Total verified entries now: {total}")

    # Save to CSV
    fieldnames = ["brand", "generic", "strengths", "form", "source", "verified"]
    with open(csv_path, "w", encoding="utf-8", newline="") as f:
        f.write("# DRAP Essential Medicines Formulary - Pakistan (Mega Clinical Edition v4.0)\n")
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        # Sort alphabetically by brand name for readability
        for row in sorted(current.values(), key=lambda r: r["brand"].lower()):
            writer.writerow(row)

    print(f"Successfully generated Mega DRAP Formulary with {total} entries at:\n{csv_path}")


if __name__ == "__main__":
    main()
